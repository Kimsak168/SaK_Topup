import "./lib/register-typescript.mjs";
import assert from "node:assert/strict";
process.env.VNGZZ2_GAME_BASE_URL = process.argv[2] || "http://127.0.0.1:4900/vngzz2/api";
process.env.VNGZZ2_GAME_API_KEY = "simulation-only-key";
const api = await import("../src/lib/suppliers/vngzz2.ts");
const games = await api.getVngzzGames();
assert.equal(games.length, 3);
assert.equal(api.isVngzzCheckoutSupported(games[2]), false);
assert.equal(api.getVngzzImageUrl(games[0].image_url), "http://127.0.0.1:4900/storage/v1/object/public/images/freefire.webp");
const products = await api.getVngzzProducts("mlbb");
assert.equal(products[0].price, 0.76);
assert.equal(products[1].available, false);
assert.equal((await api.getVngzzProducts("rate-limit")).length, 2);
await assert.rejects(api.getVngzzProducts("malformed"), error => error.code === "INVALID_RESPONSE");
await assert.rejects(api.getVngzzProducts("mismatch"), error => error.code === "GAME_MISMATCH");
await assert.rejects(api.getVngzzProducts("server-error"), error => error.code === "INVALID_RESPONSE");
process.env.VNGZZ2_GAME_TIMEOUT_MS = "100";
await assert.rejects(api.getVngzzProducts("slow"), error => error.code === "UNREACHABLE");
delete process.env.VNGZZ2_GAME_TIMEOUT_MS;
const reference = `SIM-${Date.now()}`;
const order = { productCode: "MLBB_55", playerId: "fixture-player", serverId: "fixture-zone", reference };
const first = await api.createVngzzOrder(order);
assert.equal(first.status, "completed");
assert.equal((await api.createVngzzOrder(order)).id, first.id);
assert.equal((await api.checkVngzzOrder(reference)).id, first.id);
await assert.rejects(api.createVngzzOrder({ ...order, playerId: "other-player" }), error => error.status === 409);
assert.equal((await api.createVngzzOrder({ ...order, reference: `pending-${reference}` })).status, "processing", "A success envelope must not imply delivery");
await assert.rejects(api.checkVngzzOrder("does-not-exist"), error => error.status === 404);
console.log("VNGZZ2 game API local HTTP simulation passed: catalogue responses, rate limits, malformed responses, timeouts, idempotency conflicts and order status checks. No provider purchases were sent.");
